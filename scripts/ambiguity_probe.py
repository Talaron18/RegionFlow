"""
Target ambiguity probe, GATE_A_REOPENING_PLAN.md SS7 "The corrected
ambiguity probe" -- the one thing both the proposal and its critique agree
should run before any Gate A retrain. numpy over the existing triplet
cache (transport/data.py), no GPU.

WHAT THIS TESTS, AND WHY THIS FORM NOT THE ORIGINAL ONE. The original probe
idea -- cos(v_i, v_j) across samples "sharing similar (z,c,M)" -- is
confounded: a low cosine could mean genuine mode ambiguity (same intent,
different valid edit) or just that the two images are different. The cache
has no fixed (z,c,M) with multiple recorded targets, so p(v|z,c,M) isn't
directly measurable that way.

What IS measurable is a contrast between two groupings of v = z_tgt - z_src:

  same_instruction  -- same instruction string, different source images.
  same_source       -- same source image, different instructions (the
                       INTENDED null: holds z fixed, varies only c).

THE RIGHT NUMBER TO READ OFF THIS, per a second-pass review of the first
run's result. For unit vectors, the mean pairwise cosine within a group of
n iid draws is an UNBIASED estimator of |mu|^2 (the squared length of the
population mean direction) for ANY n >= 2, not just asymptotically --
verified numerically before trusting it here (E[v_i . v_j] = E[v_i].E[v_j]
for independent i != j, exactly, regardless of group size). So
sqrt(mean pairwise cosine) is the best cosine a constant vector -- the
best possible instruction-conditioned prediction ignoring z entirely, the
exact thing E[v|c] would be -- can achieve against a fresh draw from that
group. That is the number worth reporting as a CEILING, not the raw mean
cosine itself; report() below prints both.

STATISTICAL CAVEAT, from the same review. 177 same-instruction pairs drawn
from 110 groups are NOT independent observations -- groups of size >2
contribute multiple pairs sharing a member, and a pair-level significance
test (e.g. Mann-Whitney on the raw pairs) is therefore optimistic. The
bootstrap CI in bootstrap_ceiling_gap resamples INSTRUCTION GROUPS with
replacement (the actual independent unit) rather than pairs, for an honest
uncertainty estimate on the ceiling gap.

WHAT THE UNRELATED-PAIRS FALLBACK CANNOT DO. same_source is not measurable
in THIS cache -- not because it is structurally unavailable (MagicBrush is
multi-turn; turns 2+ give the same source under a different instruction
directly -- this cache kept turn 1 only, so it is a cache-rebuild question,
not a dead end) but because rebuilding the cache needs the GPU-side
encoders. The "unrelated" pairs used instead vary BOTH z and c, so the gap
against same-instruction conflates "the instruction carries information"
with "different instructions happen to correlate with each other" -- it is
not a clean floor. Read the unrelated-pairs numbers as a weaker substitute,
not as same_source.

TWO CHEAP CHECKS ADDED, both still CPU-only on the cache as built:
  --mask-restrict   recompute every cosine with v MEAN-POOLED OVER THE MASK
                    first (one C-dim vector per item: the average per-channel
                    shift inside the edited region), not a pointwise
                    spatial cosine over the full (C,H,W) tensor. A first
                    version did the pointwise version and it was wrong: two
                    different images' edit regions almost never occupy the
                    same latent pixels, so a pointwise dot product is
                    dominated by spatial non-overlap (median cosine exactly
                    0 for both groups) regardless of whether the underlying
                    edit direction agrees. Pooling over the mask first
                    removes that confound -- it asks "did the colour/feature
                    channels move the same way", not "did they move at the
                    same pixel". MagicBrush targets are generated by
                    inpainting, which can shift the whole frame slightly
                    even outside the mask; if the unrelated-pairs floor is
                    partly that artifact, restricting to the mask should
                    move both numbers and the gap needs re-reading.
  specificity split  same-instruction pairs, split by whether the
                    instruction names a concrete attribute (a colour word)
                    or not. A coarse proxy, not an NLP classifier -- but it
                    targets the ambiguity claim directly: if underspecified
                    instructions ("change the colour") show markedly lower
                    within-group cosine than specific ones ("make it red"),
                    that is evidence FOR genuine target ambiguity rather
                    than source-dependence, which the aggregate gap alone
                    cannot distinguish.

USAGE
    python ambiguity_probe.py --self-test
    python ambiguity_probe.py --cache /path/to/cache/<hash>
    python ambiguity_probe.py --cache /path/to/cache/<hash> --mask-restrict
"""
from __future__ import annotations

import argparse
import collections
import itertools
import json
import re
from pathlib import Path

import numpy as np

#: Coarse specificity proxy -- see module docstring. Not exhaustive, not an
#: NLP model; a first, cheap cut at "does this instruction name a concrete
#: attribute" for the common colour-change case this project's own examples
#: keep using ("turn the dog brown").
_COLOR_WORDS = {
    "red", "blue", "green", "yellow", "black", "white", "brown", "pink",
    "purple", "orange", "gray", "grey", "silver", "gold", "golden", "beige",
    "maroon", "navy", "teal", "tan", "cream", "violet", "turquoise",
    "magenta", "burgundy", "khaki", "lavender", "olive", "crimson",
}


def instruction_specificity(instruction: str) -> str:
    """'specific' if the instruction names a concrete colour, 'vague'
    otherwise. See module docstring for what this can and cannot show."""
    words = set(re.findall(r"[a-z]+", instruction.lower()))
    return "specific" if words & _COLOR_WORDS else "vague"


def cosine(a: np.ndarray, b: np.ndarray) -> float:
    a, b = a.ravel(), b.ravel()
    na, nb = np.linalg.norm(a), np.linalg.norm(b)
    if na < 1e-8 or nb < 1e-8:
        return float("nan")
    return float(np.dot(a, b) / (na * nb))


def cosines_for(pairs: list[tuple[str, str]], vecs: dict) -> np.ndarray:
    return np.array([cosine(vecs[a], vecs[b]) for a, b in pairs])


def mean_pool_in_mask(v: np.ndarray, mask: np.ndarray | None) -> np.ndarray:
    """Per-channel mean of v inside the mask -> a C-dim vector.

    v is (C, H, W), mask broadcasts against v's last two dims (typically
    (1, H, W)). Pooling over space BEFORE cosine is deliberate: it asks
    "did the channels move the same way inside the edited region", not
    "did they move at the same pixel". The latter -- a pointwise spatial
    cosine over the full masked tensor -- is what a first version of this
    check did, and it was wrong: two different images' edit regions almost
    never occupy the same latent pixels, so the dot product is dominated
    by spatial non-overlap regardless of whether the edit direction
    agrees. See module docstring.
    """
    if mask is None:
        return v.reshape(v.shape[0], -1).mean(axis=1)
    m = np.broadcast_to(mask, v.shape).astype(np.float64)
    denom = m.sum(axis=(1, 2))
    num = (v * m).sum(axis=(1, 2))
    return np.divide(num, denom, out=np.zeros_like(num), where=denom > 1e-8)


def build_groups(ids: list[str], instruction_of: dict, source_of: dict):
    """Group ids by instruction string and by source-image id.

    source_of[id] is the part of the cache item id before "_t<turn>"
    (scripts/precompute_cache.py: item_id = f"{row['img_id']}_t{turn}").
    Turn is always 1 in this cache (docstring: "turn_index == 1 only"), so
    this recovers the underlying MagicBrush image id.
    """
    by_instruction = collections.defaultdict(list)
    by_source = collections.defaultdict(list)
    for i in ids:
        by_instruction[instruction_of[i]].append(i)
        by_source[source_of[i]].append(i)
    return by_instruction, by_source


def sample_pair_ids(groups: dict, rng: np.random.Generator,
                    max_pairs: int, label: str) -> list[tuple[str, str]]:
    pairs = []
    for members in groups.values():
        if len(members) < 2:
            continue
        pairs.extend(itertools.combinations(members, 2))
    n_groups = sum(1 for m in groups.values() if len(m) >= 2)
    print(f"  {label}: {len(pairs)} candidate pairs across {n_groups} "
          f"groups with >=2 members")
    if not pairs:
        return []
    if len(pairs) > max_pairs:
        idx = rng.choice(len(pairs), max_pairs, replace=False)
        pairs = [pairs[k] for k in idx]
    return pairs


def sample_unrelated_pair_ids(ids: list[str], instruction_of: dict,
                              rng: np.random.Generator,
                              n_pairs: int) -> list[tuple[str, str]]:
    """Null baseline: random pairs with DIFFERENT instructions (source may
    or may not match -- with same-source empty in practice this is moot,
    but excluded explicitly anyway so the null can't accidentally include
    a same-source pair the main run couldn't find).

    NOT a clean floor -- see module docstring's "WHAT THE UNRELATED-PAIRS
    FALLBACK CANNOT DO". Added only because without SOME null, the
    same-instruction cosine has nothing to be compared against at all.
    """
    n = len(ids)
    got, tries, max_tries = [], 0, n_pairs * 50
    while len(got) < n_pairs and tries < max_tries:
        tries += 1
        i, j = rng.integers(0, n), rng.integers(0, n)
        if i == j:
            continue
        a, b = ids[i], ids[j]
        if instruction_of[a] == instruction_of[b]:
            continue
        got.append((a, b))
    print(f"  unrelated (different instruction, random source): "
          f"{len(got)} pairs sampled")
    return got


def report(name: str, arr: np.ndarray) -> None:
    arr = arr[~np.isnan(arr)]
    if arr.size == 0:
        print(f"  {name}: no pairs (nothing to report)")
        return
    ceiling = np.sqrt(max(float(arr.mean()), 0.0))
    print(f"  {name}: n={arr.size}  mean {arr.mean():+.3f}  "
          f"median {np.median(arr):+.3f}  "
          f"p10 {np.percentile(arr, 10):+.3f}  "
          f"p90 {np.percentile(arr, 90):+.3f}  "
          f"ceiling=sqrt(mean)={ceiling:.3f}")


def bootstrap_ceiling_gap(by_instruction: dict, null_pairs: list, vecs: dict,
                          rng: np.random.Generator, n_boot: int = 2000,
                          max_pairs: int = 5000):
    """Percentile CI for the ceiling gap
    (sqrt(mean same-instruction cos) - sqrt(mean null cos)), resampling
    INSTRUCTION GROUPS with replacement for the same-instruction side --
    not individual pairs. See module docstring's "STATISTICAL CAVEAT" for
    why a pair-level test overstates confidence here. The null side
    resamples its own pairs directly (already close to independent draws
    over distinct random items, unlike the grouped same-instruction side).

    Returns (median_gap, lo95, hi95), or None if either side has nothing
    to resample.
    """
    groups = [g for g in by_instruction.values() if len(g) >= 2]
    if not groups or not null_pairs:
        return None
    gaps = []
    for _ in range(n_boot):
        idx = rng.integers(0, len(groups), len(groups))
        pairs = []
        for gi in idx:
            pairs.extend(itertools.combinations(groups[gi], 2))
        if len(pairs) > max_pairs:
            sel = rng.choice(len(pairs), max_pairs, replace=False)
            pairs = [pairs[k] for k in sel]
        si = cosines_for(pairs, vecs)
        si = si[~np.isnan(si)]

        nidx = rng.integers(0, len(null_pairs), len(null_pairs))
        n_boot_pairs = [null_pairs[k] for k in nidx]
        nu = cosines_for(n_boot_pairs, vecs)
        nu = nu[~np.isnan(nu)]

        if si.size == 0 or nu.size == 0:
            continue
        gaps.append(np.sqrt(max(si.mean(), 0.0)) - np.sqrt(max(nu.mean(), 0.0)))
    if not gaps:
        return None
    lo, hi = np.percentile(gaps, [2.5, 97.5])
    return float(np.median(gaps)), float(lo), float(hi)


def run(cache_root: Path, max_pairs: int, seed: int,
       mask_restrict: bool = False) -> None:
    meta = json.loads((cache_root / "meta.json").read_text())
    items = meta["items"]
    print(f"{len(items)} cached triplets in {cache_root}")

    vecs, masks, instruction_of, source_of = {}, {}, {}, {}
    for rec in items:
        d = np.load(cache_root / f"{rec['stem']}.npz")
        v = d["z_tgt"].astype(np.float64) - d["z_src"].astype(np.float64)
        vecs[rec["id"]] = v
        masks[rec["id"]] = d["mask"].astype(np.float64) if "mask" in d.files else None
        instruction_of[rec["id"]] = rec["instruction"]
        source_of[rec["id"]] = rec["id"].rsplit("_t", 1)[0]

    ids = list(vecs)
    by_instruction, by_source = build_groups(ids, instruction_of, source_of)
    rng = np.random.default_rng(seed)

    print("\npair availability:")
    same_instr_pairs = sample_pair_ids(by_instruction, rng, max_pairs,
                                       "same instruction, different source")
    same_src_pairs = sample_pair_ids(by_source, rng, max_pairs,
                                     "same source, different instruction")

    same_instr_cos = cosines_for(same_instr_pairs, vecs)
    print("\ncos(v_i, v_j) -- raw v:")
    report("same-instruction", same_instr_cos)

    if same_src_pairs:
        null_pairs, null_label = same_src_pairs, "same-source"
    else:
        print("\nno same-source pairs at all: this cache keeps turn_index==1 "
              "only, so no source recurs under a different instruction. This "
              "is a cache-build choice (MagicBrush is multi-turn; turns 2+ "
              "would give this directly), not a structural dead end -- "
              "fixing it needs a cache rebuild with the GPU-side encoders, "
              "not more analysis of this cache. Falling back to an "
              "unrelated-pairs null so same-instruction has SOMETHING to be "
              "compared against; see module docstring for what that null "
              "cannot show.")
        null_pairs = sample_unrelated_pair_ids(
            ids, instruction_of, rng, len(same_instr_pairs) or max_pairs)
        null_label = "unrelated"
    null_cos = cosines_for(null_pairs, vecs)
    report(f"{null_label:<17}", null_cos)

    boot = bootstrap_ceiling_gap(by_instruction, null_pairs, vecs, rng)
    if boot:
        med, lo, hi = boot
        print(f"\nceiling gap (same-instruction minus {null_label}), "
              f"group-level bootstrap: median {med:+.3f}  95% CI [{lo:+.3f}, {hi:+.3f}]")
        if lo <= 0.0 <= hi:
            print("  CI includes 0 -- do not treat this gap as established "
                  "at 95% confidence, whatever a pair-level test said.")

    # ------------------------------------------------- specificity split --
    specific_groups = {k: v for k, v in by_instruction.items()
                       if instruction_specificity(k) == "specific"}
    vague_groups = {k: v for k, v in by_instruction.items()
                   if instruction_specificity(k) == "vague"}
    print(f"\nspecificity split ({len(specific_groups)} specific instructions, "
          f"{len(vague_groups)} vague, by the colour-word proxy -- see "
          "module docstring):")
    spec_pairs = sample_pair_ids(specific_groups, rng, max_pairs, "  specific")
    vague_pairs = sample_pair_ids(vague_groups, rng, max_pairs, "  vague")
    report("  specific same-instr", cosines_for(spec_pairs, vecs))
    report("  vague same-instr   ", cosines_for(vague_pairs, vecs))

    # ------------------------------------------------------ mask-restrict --
    if mask_restrict and any(m is not None for m in masks.values()):
        vecs_m = {i: mean_pool_in_mask(vecs[i], masks[i]) for i in ids}
        print("\ncos(v_i, v_j) -- v MEAN-POOLED OVER THE MASK REGION "
              "(per-channel, spatial location no longer matters):")
        report("same-instruction", cosines_for(same_instr_pairs, vecs_m))
        report(f"{null_label:<17}", cosines_for(null_pairs, vecs_m))
        boot_m = bootstrap_ceiling_gap(by_instruction, null_pairs, vecs_m, rng)
        if boot_m:
            med, lo, hi = boot_m
            print(f"\nceiling gap, mask-restricted, group-level bootstrap: "
                  f"median {med:+.3f}  95% CI [{lo:+.3f}, {hi:+.3f}]")
    elif mask_restrict:
        print("\n--mask-restrict requested but no cached item has a 'mask' "
              "array -- cannot restrict, skipping")


# --------------------------------------------------------------- self-test --

def self_test() -> None:
    assert abs(cosine(np.array([1.0, 0.0]), np.array([1.0, 0.0])) - 1.0) < 1e-9
    assert abs(cosine(np.array([1.0, 0.0]), np.array([0.0, 1.0]))) < 1e-9
    assert abs(cosine(np.array([1.0, 0.0]), np.array([-1.0, 0.0])) + 1.0) < 1e-9
    assert np.isnan(cosine(np.array([0.0, 0.0]), np.array([1.0, 0.0])))

    assert instruction_specificity("make it red") == "specific"
    assert instruction_specificity("change the colour") == "vague"
    assert instruction_specificity("turn the dog BROWN") == "specific"
    assert instruction_specificity("remove the object") == "vague"

    # Synthetic cache: 2 instructions x 3 sources, plus one source with two
    # different instructions (so same_source has something to group).
    # v aligned within an instruction (small perpendicular jitter), and
    # orthogonal-ish across instructions -- a controlled case where the
    # ambiguity story is TRUE, to check the probe recovers that shape.
    rng = np.random.default_rng(0)
    instr_dir = {"make it red": np.array([1.0, 0.0, 0.0]),
                 "change the colour": np.array([0.0, 1.0, 0.0])}
    vecs, instruction_of, source_of = {}, {}, {}
    idx = 0
    specs = [("src0", "make it red"), ("src1", "make it red"), ("src2", "make it red"),
             ("src0", "change the colour"), ("src3", "change the colour"),
             ("src4", "change the colour")]
    for src, instr in specs:
        jitter = rng.normal(scale=0.05, size=3)
        v = instr_dir[instr] + jitter
        item_id = f"{src}_t1_{idx}"
        idx += 1
        vecs[item_id] = v
        instruction_of[item_id] = instr
        source_of[item_id] = src

    ids = list(vecs)
    by_instruction, by_source = build_groups(ids, instruction_of, source_of)
    assert len(by_instruction["make it red"]) == 3
    assert len(by_instruction["change the colour"]) == 3
    # src0 appears under both instructions -> the only same-source group with 2+.
    assert len(by_source["src0"]) == 2
    assert len(by_source["src1"]) == 1

    rng2 = np.random.default_rng(1)
    same_instr_pairs = sample_pair_ids(by_instruction, rng2, 1000, "test")
    same_src_pairs = sample_pair_ids(by_source, rng2, 1000, "test")
    same_instr_cos = cosines_for(same_instr_pairs, vecs)
    same_src_cos = cosines_for(same_src_pairs, vecs)
    assert same_instr_cos.size == 3 + 3  # C(3,2) within each instruction
    assert same_src_cos.size == 1        # only src0 has 2 members
    assert same_instr_cos.mean() > 0.9, same_instr_cos.mean()   # near-aligned by construction
    assert same_src_cos.mean() < 0.3, same_src_cos.mean()        # near-orthogonal

    unrelated_pairs = sample_unrelated_pair_ids(ids, instruction_of, rng2, 100)
    unrelated_cos = cosines_for(unrelated_pairs, vecs)
    # every unrelated pair by construction spans the two instructions (only 2
    # exist), so it should look like same_src: near-orthogonal.
    assert unrelated_cos.size > 0
    assert unrelated_cos.mean() < 0.3, unrelated_cos.mean()

    # sqrt(mean cosine) ceiling: near-aligned group (mean cos ~1) should give
    # a ceiling near 1; near-orthogonal should give a ceiling near 0.
    assert np.sqrt(max(same_instr_cos.mean(), 0.0)) > 0.9
    assert np.sqrt(max(unrelated_cos.mean(), 0.0)) < 0.6

    # bootstrap_ceiling_gap: the TRUE gap here is large and unambiguous by
    # construction (aligned vs orthogonal groups) -- the CI must exclude 0
    # and sit close to the ceiling gap computed directly above.
    boot = bootstrap_ceiling_gap(by_instruction, unrelated_pairs, vecs,
                                 np.random.default_rng(2), n_boot=500)
    assert boot is not None
    med, lo, hi = boot
    assert lo > 0.2, (med, lo, hi)  # CI must exclude 0 given the huge true gap

    # mean_pool_in_mask on the earlier 1-D toy vectors (C=3, no spatial
    # dims): a mask that zeros out the axis carrying the aligned signal
    # must collapse same-instruction cosine towards the jitter's own
    # near-zero correlation, matching the old inline-multiply check this
    # replaces (mean_pool_in_mask needs (C,H,W); reshape C-vectors to
    # (C,1,1) and the mask to (1,1,1) so pooling is a no-op multiply here).
    zero_signal_mask = np.array([0.0, 1.0, 1.0]).reshape(3, 1, 1)  # kills
    # axis 0, where BOTH instr_dir vectors differ (red is axis0,
    # colour-change is axis1) -- for "make it red" this removes all signal.
    vecs_3d = {i: vecs[i].reshape(3, 1, 1) for i in ids}
    vecs_m2 = {i: mean_pool_in_mask(vecs_3d[i], zero_signal_mask) for i in ids}
    red_pairs = [(a, b) for a, b in same_instr_pairs
                if instruction_of[a] == "make it red"]
    assert cosines_for(red_pairs, vecs_m2).mean() < cosines_for(red_pairs, vecs).mean()

    # The actual bug being fixed: a genuine (C,H,W) case where two items'
    # edit regions sit at DIFFERENT spatial locations but move the SAME
    # per-channel direction. A naive pointwise-then-cosine over the full
    # masked tensor gives ~0 (no spatial overlap); mean-pooling over the
    # mask first must recover the true alignment (~1).
    C, H, W = 4, 8, 8
    direction = np.array([1.0, 0.5, -0.3, 0.2])
    v_a = np.zeros((C, H, W)); v_a[:, 0:2, 0:2] = direction[:, None, None]
    v_b = np.zeros((C, H, W)); v_b[:, 6:8, 6:8] = direction[:, None, None]
    mask_a = np.zeros((1, H, W)); mask_a[:, 0:2, 0:2] = 1.0
    mask_b = np.zeros((1, H, W)); mask_b[:, 6:8, 6:8] = 1.0
    pointwise_cos = cosine(v_a * mask_a, v_b * mask_b)
    assert abs(pointwise_cos) < 1e-8, pointwise_cos  # the bug: no overlap -> 0
    pooled_a = mean_pool_in_mask(v_a, mask_a)
    pooled_b = mean_pool_in_mask(v_b, mask_b)
    assert cosine(pooled_a, pooled_b) > 0.99  # the fix: recovers the true match

    print("ambiguity_probe self-test OK")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--cache", type=Path, default=None)
    p.add_argument("--max-pairs", type=int, default=5000,
                   help="cap on sampled pairs per group, for cost")
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--mask-restrict", action="store_true",
                   help="also recompute every cosine with v restricted to "
                        "the mask region")
    p.add_argument("--self-test", action="store_true")
    args = p.parse_args()

    if args.self_test:
        self_test()
        return
    if args.cache is None:
        p.error("--cache is required (or pass --self-test)")
    run(args.cache, args.max_pairs, args.seed, mask_restrict=args.mask_restrict)


if __name__ == "__main__":
    main()
